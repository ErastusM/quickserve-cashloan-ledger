// Packs the built admin console (_site/, from site/assemble.sh) into one
// Cloudflare Worker script, dist/worker.js. The console is a single HTML file,
// so it fits inside the Worker itself and needs no separate asset upload.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const site = join(here, "..", "..", "_site");
const read = (f) => readFileSync(join(site, f), "utf8");
const root = join(here, "..", "..");
const b64 = (f) => readFileSync(join(root, f)).toString("base64");
const files = {
  index: read("index.html"), notFound: read("404.html"), sw: read("sw.js"),
  pushSw: readFileSync(join(here, "push-sw.js"), "utf8"),
  manifest: JSON.stringify({
    name: "QuickServe Admin", short_name: "QuickServe", start_url: "/", scope: "/", display: "standalone",
    background_color: "#0a1c14", theme_color: "#0a1c14",
    icons: [
      { src: "/icon-192.png", sizes: "192x192", type: "image/png" },
      { src: "/icon-512.png", sizes: "512x512", type: "image/png" },
      { src: "/icon-maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" }
    ]
  })
};
const IMAGES = {
  "/icon-192.png": b64("icon-192.png"), "/icon-512.png": b64("icon-512.png"),
  "/icon-maskable-512.png": b64("icon-maskable-512.png"), "/apple-touch-icon.png": b64("apple-touch-icon.png")
};

const worker = `// Generated by site/admin-worker/build.mjs. Do not edit.
const FILES = ${JSON.stringify(files)};
const IMAGES = ${JSON.stringify(IMAGES)};
function png(b64) { const bin = atob(b64), out = new Uint8Array(bin.length); for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i); return out; }
const SECURITY = {
  "X-Content-Type-Options": "nosniff",
  "X-Frame-Options": "DENY",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "Strict-Transport-Security": "max-age=31536000"
};
function page(body, type, status, cache) {
  return new Response(body, { status, headers: { "Content-Type": type, "Cache-Control": cache, ...SECURITY } });
}
export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (request.method !== "GET" && request.method !== "HEAD") return new Response("Method not allowed", { status: 405 });
    if (url.pathname === "/admin") return Response.redirect(url.origin + "/admin/", 301);
    if (url.pathname === "/" || url.pathname === "/index.html" || url.pathname === "/admin/" || url.pathname === "/admin/index.html")
      return page(FILES.index, "text/html; charset=utf-8", 200, "no-cache");
    if (url.pathname === "/sw.js") return page(FILES.sw, "text/javascript; charset=utf-8", 200, "no-cache");
    if (url.pathname === "/push-sw.js") return page(FILES.pushSw, "text/javascript; charset=utf-8", 200, "no-cache");
    if (url.pathname === "/manifest.webmanifest") return page(FILES.manifest, "application/manifest+json", 200, "no-cache");
    if (IMAGES[url.pathname]) return page(png(IMAGES[url.pathname]), "image/png", 200, "public, max-age=86400");
    return page(FILES.notFound, "text/html; charset=utf-8", 404, "no-cache");
  }
};
`;
mkdirSync(join(here, "dist"), { recursive: true });
writeFileSync(join(here, "dist", "worker.js"), worker);
console.log("dist/worker.js", Buffer.byteLength(worker), "bytes");
