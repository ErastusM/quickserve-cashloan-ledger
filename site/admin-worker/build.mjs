// Packs the built admin console (_site/, from site/assemble.sh) into one
// Cloudflare Worker script, dist/worker.js. The console is a single HTML file,
// so it fits inside the Worker itself and needs no separate asset upload.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const site = join(here, "..", "..", "_site");
const read = (f) => readFileSync(join(site, f), "utf8");
const files = { index: read("index.html"), notFound: read("404.html"), sw: read("sw.js") };

const worker = `// Generated by site/admin-worker/build.mjs. Do not edit.
const FILES = ${JSON.stringify(files)};
const SECURITY = {
  "X-Content-Type-Options": "nosniff",
  "X-Frame-Options": "DENY",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "Strict-Transport-Security": "max-age=31536000"
};
function page(body, type, status, cache) {
  return new Response(body, { status, headers: { "Content-Type": type, "Cache-Control": cache, ...SECURITY } });
}
export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (request.method !== "GET" && request.method !== "HEAD") return new Response("Method not allowed", { status: 405 });
    if (url.pathname === "/admin") return Response.redirect(url.origin + "/admin/", 301);
    if (url.pathname === "/" || url.pathname === "/index.html" || url.pathname === "/admin/" || url.pathname === "/admin/index.html")
      return page(FILES.index, "text/html; charset=utf-8", 200, "no-cache");
    if (url.pathname === "/sw.js") return page(FILES.sw, "text/javascript; charset=utf-8", 200, "no-cache");
    return page(FILES.notFound, "text/html; charset=utf-8", 404, "no-cache");
  }
};
`;
mkdirSync(join(here, "dist"), { recursive: true });
writeFileSync(join(here, "dist", "worker.js"), worker);
console.log("dist/worker.js", Buffer.byteLength(worker), "bytes");
