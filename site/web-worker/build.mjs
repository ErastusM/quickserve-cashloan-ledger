// Packs the public website (web/) into one Cloudflare Worker script,
// site/web-worker/dist/worker.js. Shared head, header and footer come from
// web/_partials and are stitched into each page here.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, extname } from "node:path";
import { execSync } from "node:child_process";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "..", "..", "web");
let commit = "local";
try { commit = execSync("git rev-parse --short HEAD", { cwd: web }).toString().trim(); } catch {}
const BUILD = new Date().toISOString().slice(0, 10).replace(/-/g, "") + "-" + commit;
const partial = (n) => readFileSync(join(web, "_partials", n + ".html"), "utf8").trim();
const parts = { head: partial("head"), header: partial("header"), footer: partial("footer") };
const DESK_PAGES = new Set(["track.html", "404.html"]); // pages whose last band is the teal desk

const TYPES = { ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".svg": "image/svg+xml" };
const files = {};
for (const name of readdirSync(web)) {
  const ext = extname(name);
  if (!TYPES[ext]) continue;
  let body = readFileSync(join(web, name), "utf8");
  if (ext === ".html") {
    body = body
      .replace("<!--#head-->", parts.head)
      .replace("<!--#header-->", parts.header)
      .replace("<!--#footer-->", parts.footer.replace("__EDGE__", DESK_PAGES.has(name) ? ' style="--edge:var(--desk)"' : ""));
    if (/<!--#/.test(body)) throw new Error(name + ": unknown partial");
  }
  files["/" + name] = { type: TYPES[ext], body: body.replace(/__BUILD__/g, BUILD) };
}
for (const need of ["/soon.html", "/index.html", "/apply.html", "/track.html", "/privacy.html", "/404.html"]) {
  if (!files[need]) throw new Error("missing " + need);
}

const worker = `// Generated by site/web-worker/build.mjs (${BUILD}). Do not edit.
const FILES = ${JSON.stringify(files)};
const PAGES = { "/": "/index.html", "/apply": "/apply.html", "/track": "/track.html", "/privacy": "/privacy.html" };
const CSP = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' https://challenges.cloudflare.com https://static.cloudflareinsights.com",
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "font-src https://fonts.gstatic.com",
  "img-src 'self' data: blob:",
  "connect-src 'self' https://api.quickserve.group https://cloudflareinsights.com",
  "frame-src https://challenges.cloudflare.com",
  "form-action 'self'",
  "base-uri 'self'",
  "frame-ancestors 'none'"
].join("; ");
function send(file, status, hidden) {
  const h = {
    "Content-Type": file.type,
    "Cache-Control": file.type.startsWith("text/html") ? "no-cache" : "public, max-age=3600",
    "X-Content-Type-Options": "nosniff",
    "Referrer-Policy": "strict-origin-when-cross-origin",
    "Strict-Transport-Security": "max-age=31536000",
    "Permissions-Policy": "camera=(self), geolocation=(), microphone=()"
  };
  if (file.type.startsWith("text/html")) { h["Content-Security-Policy"] = CSP; h["X-Frame-Options"] = "DENY"; }
  if (hidden) h["X-Robots-Tag"] = "noindex, nofollow";
  return new Response(file.body, { status, headers: h });
}
export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    if (url.hostname.startsWith("www.")) return Response.redirect("https://" + url.hostname.slice(4) + url.pathname + url.search, 301);
    if (request.method !== "GET" && request.method !== "HEAD") return new Response("Method not allowed", { status: 405 });
    // The preview address (and preview mode) is never indexed by search engines.
    const hidden = env.SITE_MODE === "preview" || url.hostname.startsWith("preview.");
    let path = url.pathname.replace(/\\/+$/, "") || "/";
    if (path === "/robots.txt") {
      const body = hidden ? "User-agent: *\\nDisallow: /\\n" : "User-agent: *\\nDisallow: /apply\\nDisallow: /track\\nSitemap: https://quickserve.group/sitemap.xml\\n";
      return new Response(body, { headers: { "Content-Type": "text/plain" } });
    }
    if (path === "/sitemap.xml") {
      const urls = ["/", "/privacy"].map((p) => "<url><loc>https://quickserve.group" + p + "</loc></url>").join("");
      return new Response('<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' + urls + "</urlset>", { headers: { "Content-Type": "application/xml" } });
    }
    // SITE_MODE "soon": quickserve.group shows only the coming-soon page (and
    // the privacy notice). preview.quickserve.group keeps the full site.
    const soon = env.SITE_MODE === "soon" && !url.hostname.startsWith("preview.");
    if (soon) {
      if (path === "/privacy" || path === "/privacy.html") return send(FILES["/privacy.html"], 200, hidden);
      if (/\\.(css|js|svg)$/.test(path) && FILES[path]) return send(FILES[path], 200, hidden);
      if (path !== "/") return Response.redirect(url.origin + "/", 302);
      return send(FILES["/soon.html"], 200, hidden);
    }
    if (path === "/soon.html") return send(FILES["/404.html"], 404, hidden);
    const pretty = Object.keys(PAGES).find((k) => PAGES[k] === path);
    if (pretty) return Response.redirect(url.origin + pretty + url.search, 301);
    const file = FILES[PAGES[path] || path];
    if (file && !path.startsWith("/_")) return send(file, 200, hidden);
    return send(FILES["/404.html"], 404, hidden);
  }
};
`;
mkdirSync(join(here, "dist"), { recursive: true });
writeFileSync(join(here, "dist", "worker.js"), worker);
console.log("site/web-worker/dist/worker.js", Buffer.byteLength(worker), "bytes, build", BUILD);
